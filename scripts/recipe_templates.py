def _strip_method(name: str) -> str:
    """Strip the longest matching PREFIX from the dish name to recover the
    base ingredient phrase (used as {core} in templates)."""
    for prefix, _ in PREFIX_TEMPLATES:
        if name.startswith(prefix) and len(name) > len(prefix):
            return name[len(prefix):]
    return name


def generate_recipe(name: str) -> str:
    """Return a brief Chinese cooking instruction for the given dish name.

    Strategy: try EXACT → PREFIX → SUFFIX → INGREDIENT → FALLBACK.
    """
    if not name:
        return FALLBACK_RECIPE

    # 1. Exact override
    if name in INGREDIENT_RECIPES:
        return INGREDIENT_RECIPES[name]

    # 2. Prefix (use the longest matching prefix to avoid e.g. "烤" winning
    #    over "慢烤" for a dish starting with "慢烤牛排").
    for prefix, template in sorted(PREFIX_TEMPLATES, key=lambda kv: len(kv[0]), reverse=True):
        if template and name.startswith(prefix) and len(name) > len(prefix):
            core = _strip_method(name)
            return template.replace("{}", name).format(core=core)

    # 3. Suffix
    for suffix, template in sorted(SUFFIX_TEMPLATES, key=lambda kv: len(kv[0]), reverse=True):
        if name.endswith(suffix) and len(name) > len(suffix):
            core = name[: -len(suffix)]
            return template.replace("{}", name).format(core=core)

    # 4. Ingredient keyword (longest first to prefer specific matches)
    for keyword, template in sorted(INGREDIENT_TEMPLATES, key=lambda kv: len(kv[0]), reverse=True):
        if keyword in name:
            return template.replace("{}", name).format(core=name)

    # 5. Fallback
    return FALLBACK_RECIPE.replace("{core}", name)
